import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import radarHandler from './api/radar.js'

function radarDevPlugin() {
  return {
    name: 'radar-dev-server',
    configureServer(server) {
      server.middlewares.use(async (req, res, next) => {
        if (req.url && req.url.startsWith('/api/radar')) {
          try {
            await radarHandler(req, res);
          } catch (e) {
            res.statusCode = 500;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ error: e.message }));
          }
          return;
        }
        next();
      });
    }
  };
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), radarDevPlugin()],
  server: {
    proxy: {
      '/serpapi': {
        target: 'https://serpapi.com',
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/serpapi/, '')
      }
    }
  }
})
